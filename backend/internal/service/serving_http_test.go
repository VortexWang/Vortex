func servingHTTP(t *testing.T, f *portFixture) (http.Handler, string) {
	t.Helper()
	tokens := &auth.Tokens{Store: repository.TokenRepository{Pool: f.pool}, AccessTTL: time.Minute, RefreshTTL: time.Hour}
	p, e := auth.NewPrincipal(f.scope.ActorID(), f.tenant, auth.Owner, "active")
	if e != nil {
		t.Fatal(e)
	}
	pair, e := tokens.Issue(context.Background(), p, uuid.NewString())
	if e != nil {
		t.Fatal(e)
	}
	cursors, e := httpapi.NewCursorCodec([]byte(strings.Repeat("serving-api-test", 3)), time.Hour)
	if e != nil {
		t.Fatal(e)
	}
	h, e := httpapi.NewRouter(httpapi.Config{Pool: f.pool, Tokens: tokens, Cursors: cursors})
	if e != nil {
		t.Fatal(e)
	}
	return h, pair.AccessToken
}
func servingCall(h http.Handler, token, method, path, key, body string) *httptest.ResponseRecorder {
	r := httptest.NewRequest(method, path, strings.NewReader(body))
	r.Header.Set("Authorization", "Bearer "+token)
	if body != "" {
		r.Header.Set("Content-Type", "application/json")
	}
	if key != "" {
		r.Header.Set("Idempotency-Key", key)
	}
	w := httptest.NewRecorder()
	h.ServeHTTP(w, r)
	return w
}
func TestServingHTTPConfirmedAddressesDNSExactReplayAfterHealthChange(t *testing.T) {
	f, _, access, provider := dnsFixture(t)
	ctx := context.Background()
	h, token := servingHTTP(t, f)
	// Public addresses intentionally contain only business entry IPs.
	if _, e := f.pool.Exec(ctx, `UPDATE nodes SET public_address='192.0.2.41' WHERE id=ANY($1::text[])`, f.nodes); e != nil {
		t.Fatal(e)
	}
	base := "/api/v1/tenants/" + f.tenant + "/node-groups/" + f.group
	w := servingCall(h, token, "GET", base+"/serving", "", "")
	if w.Code != 200 || w.Body.String() != `{"addresses":[]}` {
		t.Fatal(w.Code, w.Body)
	}
	a := f.prepare(t, 20000)
	f.commit(t, a)
	w = servingCall(h, token, "GET", base+"/serving", "", "")
	if w.Code != 200 || w.Body.String() != `{"addresses":["192.0.2.41"]}` {
		t.Fatal(w.Code, w.Body)
	}
	input := `{"access_id":"` + access + `","name":"` + f.group + `.example.test"}`
	key := uuid.NewString()
	responses := make(chan *httptest.ResponseRecorder, 8)
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() { defer wg.Done(); responses <- servingCall(h, token, "POST", base+"/dns", key, input) }()
	}
	wg.Wait()
	close(responses)
	var id, accepted string
	for w := range responses {
		var b struct {
			Operation string `json:"operation_id"`
			State     string `json:"state"`
		}
		if e := json.Unmarshal(w.Body.Bytes(), &b); e != nil || w.Code != 202 || b.Operation == "" || b.State != "pending" {
			t.Fatal(w.Code, w.Body, e)
		}
		if id != "" && (b.Operation != id || w.Body.String() != accepted) {
			t.Fatal("retry changed accepted identity", id, w.Body)
		}
		id, accepted = b.Operation, w.Body.String()
		if !strings.HasSuffix(w.Header().Get("Location"), "/"+id) {
			t.Fatal(w.Header())
		}
		for _, secret := range []string{"access_id", "zone_id", "ciphertext", "nonce", "addresses", "boot_id", "payload", "token"} {
			if strings.Contains(w.Body.String(), secret) {
				t.Fatal("internal DNS field exposed", w.Body)
			}
		}
	}
	if provider.calls != 0 {
		t.Fatal("HTTP executed external DNS", provider.calls)
	}
	if _, e := f.pool.Exec(ctx, `UPDATE nodes SET health='unhealthy' WHERE id=ANY($1::text[])`, f.nodes); e != nil {
		t.Fatal(e)
	}
	if w = servingCall(h, token, "GET", base+"/serving", "", ""); w.Code != 200 || w.Body.String() != `{"addresses":[]}` {
		t.Fatal(w.Code, w.Body)
	}
	if w = servingCall(h, token, "POST", base+"/dns", key, input); w.Code != 202 || w.Body.String() != accepted {
		t.Fatal("accepted snapshot changed on retry", w.Code, w.Body)
	}
	var tasks, held int
	if e := f.pool.QueryRow(ctx, `SELECT (SELECT count(*) FROM operations WHERE tenant_id=$1 AND idempotency_key=$2),(SELECT count(*) FROM port_reservations WHERE tenant_id=$1 AND state<>'released')`, f.tenant, "dns/"+key).Scan(&tasks, &held); e != nil || tasks != 1 || held != 4 {
		t.Fatal(tasks, held, e)
	}
	changed := strings.Replace(input, f.group+".example.test", "other.example.test", 1)
	if w = servingCall(h, token, "POST", base+"/dns", key, changed); w.Code != 409 {
		t.Fatal(w.Code, w.Body)
	}
}
func TestServingHTTPDNSAuditRollbackAndStrictInputs(t *testing.T) {
	f, _, access, _ := dnsFixture(t)
	h, token := servingHTTP(t, f)
	base := "/api/v1/tenants/" + f.tenant + "/node-groups/" + f.group
	input := `{"access_id":"` + access + `","name":"` + f.group + `.example.test"}`
	// Request IDs are generated by HTTP, so bind the fault to the exact business
	// audit action and fixture tenant rather than a user-controlled request ID.
	name := "serving_http_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	ctx := context.Background()
	if _, e := f.pool.Exec(ctx, `CREATE FUNCTION `+name+`() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.tenant_id='`+f.tenant+`' AND NEW.action='dns.recompute' THEN RAISE EXCEPTION 'PRIVATE injected DNS audit'; END IF; RETURN NEW; END $$;CREATE TRIGGER `+name+` BEFORE INSERT ON audit_events FOR EACH ROW EXECUTE FUNCTION `+name+`() `); e != nil {
		t.Fatal(e)
	}
	drop := func() {
		if _, e := f.pool.Exec(ctx, `DROP TRIGGER IF EXISTS `+name+` ON audit_events;DROP FUNCTION IF EXISTS `+name+`() `); e != nil {
			t.Error(e)
		}
	}
	t.Cleanup(drop)
	tables := []string{"entry_group_domains", "desired_state", "operations", "tasks", "outbox", "audit_events", "domain_events"}
	before := authoritySnapshot(t, f.pool, f.tenant, tables)
	if w := servingCall(h, token, "POST", base+"/dns", uuid.NewString(), input); w.Code != 503 || strings.Contains(w.Body.String(), "PRIVATE") {
		t.Fatal(w.Code, w.Body)
	}
	if !bytes.Equal(before, authoritySnapshot(t, f.pool, f.tenant, tables)) {
		t.Fatal("DNS audit rollback leaked authority")
	}
	drop()
	for _, body := range []string{`{}`, `{"access_id":"` + access + `","name":"UPPER.example.test"}`, `{"access_id":"` + access + `","name":"x.example.test","token":"secret"}`} {
		if w := servingCall(h, token, "POST", base+"/dns", uuid.NewString(), body); w.Code != 400 {
			t.Fatal(w.Code, w.Body)
		}
	}
	if w := servingCall(h, token, "POST", base+"/dns", "", input); w.Code != 400 {
		t.Fatal(w.Code, w.Body)
	}
	if w := servingCall(h, token, "GET", base+"/serving?boot_id=x", "", ""); w.Code != 400 {
		t.Fatal(w.Code, w.Body)
	}
	if w := servingCall(h, token, "POST", base+"/dns", uuid.NewString(), strings.Replace(input, access, uuid.NewString(), 1)); w.Code != 404 {
		t.Fatal(w.Code, w.Body)
	}
	// Current user revocation is resolved by Bearer authentication on every call.
	if _, e := f.pool.Exec(ctx, `UPDATE users SET state='suspended' WHERE id=$1`, f.scope.ActorID()); e != nil {
		t.Fatal(e)
	}
	if w := servingCall(h, token, "POST", base+"/dns", uuid.NewString(), input); w.Code != 401 {
		t.Fatal(w.Code, w.Body)
	}
}

func TestDNSReplayAcceptedSnapshotSurvivesHealthChange(t *testing.T) {
	f, _, access, _ := dnsFixture(t)
	ctx := context.Background()
	a := f.prepare(t, 20000)
	f.commit(t, a)
	svc := service.ServingService{Pool: f.pool}
	key := uuid.NewString()
	name := f.group + ".example.test"
	first, e := svc.RecomputeDNS(ctx, f.scope, f.group, access, name, key, uuid.NewString())
	if e != nil {
		t.Fatal(e)
	}
	if _, e = f.pool.Exec(ctx, `UPDATE nodes SET health='unhealthy' WHERE id=ANY($1::text[])`, f.nodes); e != nil {
		t.Fatal(e)
	}
	retry, e := svc.RecomputeDNS(ctx, f.scope, f.group, access, name, key, uuid.NewString())
	if e != nil || retry.ID != first.ID || !bytes.Equal(retry.Payload, first.Payload) {
		t.Fatal("retry did not retain accepted snapshot", retry.ID, first.ID, e)
	}
}
